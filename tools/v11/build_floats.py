"""Wrap generated WP A / B1 table fragments and the effort figure into v11 floats.

Run: python -I -B tools/v11/build_floats.py   (from paper-drafts/)
Copies each fragment into v11-professor-revision/generated/ unchanged and writes one
float file per label (float-<name>.tex). Captions carry no data; every number in a
float comes from its generated fragment. Input hashes go to floats-provenance.json.
"""
from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "v11-professor-revision" / "generated"

# label, environment, source fragment, caption, note (no numbers in captions or notes)
FLOATS = [
    ("tradeoff", "table", "evidence/v11-wpa/tex/table-threshold-check.tex",
     r"Relocation--Deletion Trade-off of the Final Cascade on Real Histories", None),
    ("missedcases", "table", "evidence/v11-wpa/tex/table-missed-recheck.tex",
     r"Real-History Missed Re-checks of the Default Cascade by Tier, Reference Class, Oracle Event, Project and Horizon", None),
    ("factorial", "table*", "evidence/v11-wpa/tex/table-factorial-summary.tex",
     r"Factorial Contrasts on Shared Observations, Averaged Across the Threshold Grid (Percentage Points)", None),
    ("lopo", "table*", "evidence/v11-wpa/tex/table-lopo.tex",
     r"Leave-One-Project-Out Threshold Selection and Held-Out Edit-Targeted Outcomes", None),
    ("exclusions", "table", "evidence/v11-wpa/tex/table-exclusions.tex",
     r"Commit Pairs and Anchors by Project and Revision Horizon, Retained and Oracle-Excluded", None),
    ("duplicates", "table", "evidence/v11-wpb1/tex/table-duplicates-085.tex",
     r"Duplicate Stress Suite on the Held-Out Seed at $\theta=0.85$ (\%)",
     r"IG: indentation guard; AG: pre-existing-copy guard; VW: variable-height window. Missed among targets needing re-check; wrong/silent among all targets; false request among preserved targets; extra requests per 100 preserved targets relative to the deployed cascade; range: exact file/start/end on surviving targets."),
]


# Display names for analysis identifiers printed in the WP A fragments (labels only; numbers untouched).
RELABEL = [
    ("order\\_by\\_scope\\_difference\\_in\\_differences", "order $\\times$ scope interaction"),
    ("cross\\_first\\_minus\\_fuzzy\\_first", "cross-file first $-$ fuzzy first"),
    ("whole\\_minus\\_local", "whole file $-$ local window"),
    ("replication/all", "controlled, replication"), ("main/all", "controlled, main"),
    ("real/own", "real, internal"), ("real/oss", "real, public"),
    ("fuzzy\\_first/local/full/", "fuzzy first, local, full, "),
    ("threshold\\_only", "threshold only"), ("full\\_cell", "full cell"),
    ("cross\\_exact", "tier 4 (other file)"), ("same\\_exact", "tier 2 (same file)"),
]


# Project identifiers in the WP A fragments -> the names used in the text and Table XXIV.
# p3/p4 identified by anchor totals (1,476 and 658 retained anchors, Table tab:projects).
PROJECTS = {"click": "Click", "flask": "Flask", "httpx": "HTTPX", "requests": "Requests", "rich": "Rich",
            "vcap": "Review portal", "tracer": "Claim tracer", "p3": "LM training", "p4": "Evidence ingestion"}


def relabel(raw: bytes) -> bytes:
    text = raw.decode("utf-8")
    for old, new in RELABEL:
        text = text.replace(old, new)
    # whole table cells only, so prose and other identifiers are never touched
    text = re.sub(r"(^|&)(\s*)(" + "|".join(PROJECTS) + r")(\s*)(?=&|\\\\)",
                  lambda m: m.group(1) + m.group(2) + PROJECTS[m.group(3)] + m.group(4), text, flags=re.M)
    return text.encode("utf-8")


def sha(raw: bytes) -> str:
    return hashlib.sha256(raw).hexdigest()


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    prov: dict[str, dict[str, str]] = {}
    for label, env, rel, caption, note in FLOATS:
        raw = (ROOT / rel).read_bytes()
        frag = f"frag-{label}.tex"
        (OUT / frag).write_bytes(relabel(raw))
        body = [f"% Generated by tools/v11/build_floats.py from {rel}; do not edit.",
                f"\\begin{{{env}}}[t]", f"\\caption{{{caption}}}\\label{{tab:{label}}}", "\\centering"]
        if b"\\resizebox" in raw:  # WP A fragments size themselves to the float
            body.append(f"\\input{{generated/{frag[:-4]}}}")
        else:  # bare tabular: scale to the float width and add the note
            body += ["\\footnotesize", f"\\resizebox{{\\linewidth}}{{!}}{{\\input{{generated/{frag[:-4]}}}}}"]
            if note:
                body += ["\\par\\smallskip", f"\\parbox{{\\linewidth}}{{\\scriptsize {note}}}"]
        body.append(f"\\end{{{env}}}")
        (OUT / f"float-{label}.tex").write_text("\n".join(body) + "\n", encoding="utf-8")
        prov[label] = {"source": rel, "sha256": sha(raw)}
    fig = OUT / "effort-v11.pdf"
    (OUT / "float-effort.tex").write_text("\n".join([
        "% Generated by tools/v11/build_floats.py; figure from tools/v11/build_effort_figure.py.",
        "\\begin{figure*}[t]", "\\centering", "\\includegraphics[width=\\textwidth]{generated/effort-v11.pdf}",
        "\\caption{Cheapest method under the additive effort model. Weights are chosen values in units of the cost of one lost anchor; each outer cell fixes the "
        "weights of a silent misplacement (horizontal) and a missed re-check (vertical), and its inner grid varies the "
        "weights of an unnecessary re-check (horizontal) and of a wrong placement that requests re-check (vertical) over "
        "the same log-spaced grid. The real-history panel omits the contextual tracker, whose rates Table~\\ref{tab:safety} "
        "reports, because its execution failures have no defined inspection cost; the evidence package reports that "
        "sensitivity separately.}\\label{fig:effort}", "\\end{figure*}"]) + "\n", encoding="utf-8")
    prov["effort"] = {"source": "v11-professor-revision/generated/effort-v11.pdf", "sha256": sha(fig.read_bytes())}
    (OUT / "floats-provenance.json").write_text(json.dumps(prov, indent=2), encoding="utf-8")
    print(f"{len(prov)} floats")


if __name__ == "__main__":
    main()
