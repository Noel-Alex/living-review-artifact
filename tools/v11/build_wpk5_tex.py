"""WP K5 macros and table from the latest evidence/v12-wpk5/summary-*.json.

Writes v11-professor-revision/generated/numbers-wpk5.tex (prefix \\wr), table-refaudit.tex (tab:refaudit) and
numbers-wpk5-provenance.json. Picked up by tools/v11/build_wpk_all.py.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / 'evidence/v12-wpk5'
GEN = ROOT / 'v11-professor-revision/generated'
STRATA = (('S-pair', 'Pair', 'Same-type pairing'), ('S-del', 'Del', 'Deleted or relocated'),
          ('S-dis', 'Dis', 'Methods disagree'), ('S-miss', 'Miss', 'Deployed misses'), ('S-aligned', 'Aligned', 'Aligned controls'),
          ('all-decided', 'All', 'All decided'))
MODELS = (('beam', 'Beam'), ('nemotron', 'Nemo'))


def fmt(x):
    return '--' if x is None else f'{x:.1f}' if isinstance(x, float) else str(x)


def main():
    found = sorted(EV.glob('summary-*.json'))
    if not found:
        print(f'{Path(__file__).name}: no summary yet; nothing written')
        return
    path = found[-1]
    s = json.loads(path.read_text(encoding='utf-8'))
    mac = {}

    def m(k, v):
        assert k.isalpha(), k
        mac['wr' + k] = v

    st = s['strata']
    for key, tag, _ in STRATA + (('S-excl', 'Excl', ''),):
        r = st[key]
        m(tag + 'N', str(r['n']))
        m(tag + 'CrossFile', str(r['cross_file_reference']))
        for model, mt in MODELS:
            if model not in r['models']:
                continue
            mr = r['models'][model]
            m(tag + mt + 'Parsed', str(mr['parsed']))
            if 'status_agree' in mr:
                m(tag + mt + 'Status', fmt(mr['status_agree']['pct']))
                m(tag + mt + 'StatusLo', fmt(mr['status_agree']['ci'][0]))
                m(tag + mt + 'StatusHi', fmt(mr['status_agree']['ci'][1]))
                m(tag + mt + 'Kappa', '--' if mr['status_kappa'] is None else f"{mr['status_kappa']:.2f}")
                for f, ft in (('exact', 'Exact'), ('near', 'Near'), ('overlap', 'Overlap')):
                    m(tag + mt + 'Loc' + ft, fmt(mr['loc_' + f]['pct']))
        if 'model_model_kappa' in r:
            m(tag + 'MMKappa', '--' if r['model_model_kappa'] is None else f"{r['model_model_kappa']:.2f}")
            m(tag + 'MMAgree', fmt(r['model_model_status_agree']['pct']))
        if 'suspect_status' in r:
            m(tag + 'Suspect', str(r['suspect_status']['k']))
            m(tag + 'SuspectPct', fmt(r['suspect_status']['pct']))
            m(tag + 'SuspectHi', fmt(r['suspect_status']['ci'][1]))
            m(tag + 'SuspectCons', str(r['suspect_status_consensus']['k']))
        if key == 'S-miss' and 'miss_suspects_lowering' in r:
            m('MissLowering', str(r['miss_suspects_lowering']))
            m('MissOther', str(r['miss_suspects_other']))
        if key == 'S-excl' and 'excluded_consensus' in r:
            for lab in ('unchanged', 'edited', 'deleted'):
                m('Excl' + lab.capitalize(), str(r['excluded_consensus'].get(lab, 0)))
    for model, mt in MODELS:
        if model in s['models']:
            m(mt + 'Unparsed', str(s['models'][model].get('unparsed', 0)))
            m(mt + 'Missing', str(s['models'][model].get('missing', 0)))
    text = '% Generated by tools/v11/build_wpk5_tex.py from ' + path.name + '; do not edit.\n' + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(mac.items()))
    (GEN / 'numbers-wpk5.tex').write_text(text, encoding='utf-8')
    rows = []
    for key, tag, label in STRATA:
        r = st[key]
        b, n = r['models'].get('beam', {}), r['models'].get('nemotron', {})
        w = r.get('within_file', {})
        cells = [str(r['n']), fmt(b.get('status_agree', {}).get('pct')), fmt(n.get('status_agree', {}).get('pct')),
                 fmt(b.get('loc_near', {}).get('pct')), fmt(n.get('loc_near', {}).get('pct')),
                 str(r.get('suspect_status', {}).get('k', '--')),
                 f"{w['suspect']['k']}/{w['n']}" if w else '--']
        rows.append(('\\midrule\n' if key == 'all-decided' else '') + label + ' & ' + ' & '.join(cells) + r' \\')
        if w:
            m(tag + 'WithinN', str(w['n']))
            m(tag + 'WithinSuspect', str(w['suspect']['k']))
            m(tag + 'WithinSuspectPct', fmt(w['suspect']['pct']))
            for lab in ('unchanged', 'edited', 'deleted'):
                m(tag + 'Within' + lab.capitalize(), str(w['suspect_consensus_as'].get(lab, 0)))
            for model, mt in MODELS:
                m(tag + 'Within' + mt + 'Status', fmt(w['status_agree'][model]['pct']))
    for model, mt in MODELS:
        m(mt + 'Lenient', str(s['models'][model].get('lenient_only', 0)))
    text = '% Generated by tools/v11/build_wpk5_tex.py from ' + path.name + '; do not edit.\n' + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(mac.items()))
    (GEN / 'numbers-wpk5.tex').write_text(text, encoding='utf-8')
    table = (r"""\begin{table}[t]
\caption{Blinded Model Adjudication of the Syntax-Tree Reference}\label{tab:refaudit}
\centering\footnotesize
\setlength{\tabcolsep}{2.5pt}
\begin{tabular}{@{}lrrrrrrr@{}}\toprule
 & & \multicolumn{2}{c}{Status (\%)} & \multicolumn{2}{c}{Start $\pm$2 (\%)} & \multicolumn{2}{c}{Suspects} \\ \cmidrule(lr){3-4}\cmidrule(lr){5-6}\cmidrule(l){7-8}
Stratum & $n$ & Beam & Nem. & Beam & Nem. & all & in file \\ \midrule
""" + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}
\tablenote{}{Agreement of two hosted language models, not people, with the reference. Each model saw the old excerpt with the reviewed lines marked and the paired new file, blind to the reference and every method. Status: unchanged, edited or deleted. Start $\pm$2: inside the paired file, over items the model places. Suspects: items on which both models contradict the reference status; in file: excluding reference locations in another file, which the input cannot show. Pooled $\kappa$ with the reference: \wrAllBeamKappa{} (Beam), \wrAllNemoKappa{} (Nemotron); between the models \wrAllMMKappa.}
\end{table}
""")
    (GEN / 'table-refaudit.tex').write_text(table, encoding='utf-8')
    (GEN / 'numbers-wpk5-provenance.json').write_text(json.dumps(dict(summary=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                                                                      macros=len(mac)), indent=1), encoding='utf-8')
    print(f'numbers-wpk5.tex: {len(mac)} macros from {path.name}')


if __name__ == '__main__':
    main()
