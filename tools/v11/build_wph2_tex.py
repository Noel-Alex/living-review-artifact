"""H2 macros and table from the latest evidence/v11-wph2/summary-*.json (no hand-typed numbers)."""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wpa_core import ROOT, sha  # noqa: E402

OUT = ROOT / 'evidence/v11-wph2'
TEX = OUT / 'tex'
SHOW = [('t0.85-deployed', 'Deployed cascade'), ('t0.85-AG', 'Pre-existing-copy guard'), ('t0.85-IG+AG+VW', 'All guards, $\\theta=.85$'),
        ('t0.55-deployed', 'Cascade, $\\theta=.55$'), ('t0.55-IG+AG+VW', 'All guards, $\\theta=.55$'), ('cascade_v1', 'Cascade v1'),
        ('tracker_adapter', 'Contextual tracker'), ('diff_drift', 'Diff drift'), ('quote_exact', 'Exact quote'), ('line_number', 'Line number')]


def pc(x):
    return '--' if x['rate'] is None else f"{100 * x['rate']:.1f}"


def main():
    path = sorted(OUT.glob('summary-*.json'))[-1]
    d = json.loads(path.read_text(encoding='utf-8'))['data']
    sel = d['selection']
    macros = {}

    def m(k, v):
        assert k.isalpha(), k
        macros[k] = v
    ov, tg, un = d['overall'], d['strata']['sample:targeted'], d['strata']['sample:uniform']
    m('hTwoN', f"{ov['n']:,}")
    m('hTwoPairs', f"{ov['pairs']:,}")
    m('hTwoRepos', str(len(d['repositories'])))
    m('hTwoTargetedN', f"{tg['n']:,}")
    m('hTwoUniformN', f"{un['n']:,}")
    m('hTwoSmallRepos', str(sum(r['flagged_small'] for r in d['repositories'].values())))
    m('hTwoExcluded', f"{sum(sum(r['excluded'].values()) for r in sel['repositories'].values()):,}")
    for key, name in (('t0.85-deployed', 'Dep'), ('t0.85-IG+AG+VW', 'All'), ('t0.55-IG+AG+VW', 'AllCal'), ('t0.55-deployed', 'Cal'),
                      ('tracker_adapter', 'Trk'), ('t0.85-AG', 'AG'), ('cascade_v1', 'Vone')):
        for stratum, sname in ((ov, ''), (tg, 'Tgt')):
            v = stratum['methods'][key]
            for metric, mname in (('accuracy', 'Acc'), ('missed', 'Miss'), ('wrong_silent', 'Silent'), ('false_recheck', 'False'),
                                  ('lost', 'Lost'), ('wrong', 'Wrong')):
                m(f'hTwo{name}{sname}{mname}', pc(v[metric]))
    m('hTwoTrkErrors', str(ov['methods']['tracker_adapter']['execution_errors']))
    b = d['bootstrap']
    m('hTwoDepAccLo', f"{100 * b['deployed_accuracy'][0]:.1f}")
    m('hTwoDepAccHi', f"{100 * b['deployed_accuracy'][1]:.1f}")
    m('hTwoDiffLo', f"{100 * b['deployed_minus_tracker_accuracy'][0]:.1f}")
    m('hTwoDiffHi', f"{100 * b['deployed_minus_tracker_accuracy'][1]:.1f}")
    m('hTwoDepMissLo', f"{100 * b['deployed_missed'][0]:.1f}")
    m('hTwoDepMissHi', f"{100 * b['deployed_missed'][1]:.1f}")
    reps = d['repositories']
    lead = sum(r['methods']['tracker_adapter']['accuracy']['rate'] > r['methods']['t0.85-deployed']['accuracy']['rate'] for r in reps.values())
    tie = sum(r['methods']['tracker_adapter']['accuracy']['rate'] == r['methods']['t0.85-deployed']['accuracy']['rate'] for r in reps.values())
    m('hTwoTrkLeadRepos', str(lead))
    m('hTwoTieRepos', str(tie))
    TEX.mkdir(exist_ok=True)
    (TEX / 'numbers-wph2.tex').write_text('% Generated by tools/v11/build_wph2_tex.py; do not edit.\n' +
                                          '\n'.join('\\newcommand{\\' + k + '}{' + v + '}' for k, v in macros.items()) + '\n', encoding='utf-8')
    rows = []
    for key, label in SHOW:
        a, t = ov['methods'][key], tg['methods'][key]
        rows.append(f"{label} & {pc(a['accuracy'])} & {pc(a['missed'])} & {pc(a['wrong_silent'])} & {pc(a['false_recheck'])} & "
                    f"{pc(t['accuracy'])} & {pc(t['missed'])} \\\\")
    (TEX / 'table-student.tex').write_text(
        '% Generated by tools/v11/build_wph2_tex.py; do not edit.\n\\begin{table}[t]\n'
        '\\caption{Student-Authored Repositories (Held Out)}\\label{tab:student}\n\\centering\\footnotesize\\setlength{\\tabcolsep}{3pt}\n'
        '\\begin{tabular}{@{}lrrrrrr@{}}\\toprule\n & \\multicolumn{4}{c}{All observations} & \\multicolumn{2}{c}{Edit-targeted} \\\\ '
        '\\cmidrule(lr){2-5}\\cmidrule(l){6-7}\nMethod & Acc & Missed & Silent & Extra & Acc & Missed \\\\ \\midrule\n' + '\n'.join(rows) +
        f"\n\\bottomrule\n\\end{{tabular}}\n\\tablenote{{}}{{Percentages over {ov['n']:,} observations ({tg['n']:,} edit-targeted) from "
        f"{len(reps)} repositories. Acc: file/start, including correct absence. Missed: changed or gone targets without a re-check request. "
        "Silent: wrong placement without a request. Extra: requests on preserved targets.}\n\\end{table}\n", encoding='utf-8')
    (TEX / 'provenance.json').write_text(json.dumps(dict(generator='tools/v11/build_wph2_tex.py', generator_sha256=sha(Path(__file__)),
                                                         inputs={path.relative_to(ROOT).as_posix(): sha(path)}, macros=macros), indent=1), encoding='utf-8')
    print(len(macros), 'macros')


if __name__ == '__main__':
    main()
