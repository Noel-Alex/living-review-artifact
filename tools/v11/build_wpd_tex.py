"""Generate WP D TeX macros and tables from evidence/v11-wpd JSON (no hand-typed numbers)."""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wpd_common import OUT, sha  # noqa: E402

TEX = OUT / "tex"


def load(name):
    return json.loads((OUT / name).read_text(encoding="utf-8"))


def esc(text: str) -> str:
    return (str(text).replace("\\", r"\textbackslash{}").replace("&", r"\&").replace("%", r"\%")
            .replace("_", r"\_").replace("#", r"\#").replace("{", r"\{").replace("}", r"\}")
            .replace("|", r"\textbar{}").replace("$", r"\$"))


def thousands(n: int) -> str:
    return f"{n:,}"


def main():
    spec, model, scan = load("state-spec.json"), load("model-check.json"), load("status-writer-scan.json")
    claims, existing, scenario_run = load("claims-d5.json"), load("existing-tests.json"), load("scenarios-tests.json")
    scen = {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted((OUT / "scenarios").glob("*.json"))}
    inv = model["invariants"]
    norm = scen["normalisation"]["observed"]
    conc = scen["concurrency_postgres"]["observed"]
    macros = {
        "wpdDepth": str(model["depth"]),
        "wpdStates": thousands(model["distinct_states"]),
        "wpdTransitions": thousands(model["transitions_explored"]),
        "wpdNotCarried": thousands(inv["active_issue_carried_unless_closed"]["violations"]),
        "wpdNotCarriedFaculty": thousands(inv["active_issue_carried_unless_closed"]["by_cause"].get("deleted by faculty", 0)),
        "wpdNotCarriedAgent": thousands(inv["active_issue_carried_unless_closed"]["by_cause"].get("deleted by agent", 0)),
        "wpdNotCarriedOther": thousands(inv["active_issue_carried_unless_closed"]["by_cause"].get("other", 0)),
        "wpdSystemResolved": str(inv["no_system_event_writes_resolved"]["violations"]),
        "wpdWriters": str(scan["writer_count"]),
        "wpdTransitionRows": str(len(spec["transitions"])),
        "wpdAppTestsCollected": str(len(existing["collected"])),
        "wpdAppTestsPassed": str(existing["counts"]["passed"]),
        "wpdAppTestsFailed": str(existing["counts"]["failed"]),
        "wpdAppTestsSkipped": str(existing["counts"]["skipped"]),
        "wpdScenarioRun": str(len(scenario_run["collected"])),
        "wpdScenarioPassed": str(scenario_run["counts"]["passed"]),
        "wpdPgVersion": ".".join(str(v) for v in conc["server_version"]),
        "wpdPgWaitSeconds": f"{[e for e in conc['concurrent']['timeline_seconds'] if e[1] == 'carry_start'][1][2]:.1f}",
        "wpdBigFileBytes": thousands(norm["unchanged_file_over_400000_bytes"]["bytes"]),
        "wpdClaimsConfirmed": str(sum(c["verdict"] == "confirmed" for c in claims["claims"])),
        "wpdClaimsPartial": str(sum(c["verdict"] == "partially true" for c in claims["claims"])),
        "wpdClaimsRefuted": str(sum(c["verdict"] == "refuted" for c in claims["claims"])),
    }
    TEX.mkdir(parents=True, exist_ok=True)
    (TEX / "numbers-wpd.tex").write_text(
        "% Generated by tools/v11/build_wpd_tex.py from evidence/v11-wpd; do not edit.\n"
        + "\n".join("\\newcommand{\\" + k + "}{" + v + "}" for k, v in macros.items()) + "\n", encoding="utf-8")

    short = {"permitted by design": "by design", "permitted but unguarded": "unguarded",
             "prohibited (no code path; see scan)": "no code path"}
    rows = []
    for t in spec["transitions"]:
        where = "; ".join(f"{Path(s['file']).name}:{s['line']}" for s in t["source"][:2])
        rows.append(f"{esc(t['event'])} & {esc(t['actor'])} & {esc(t['from'])} $\\to$ {esc(t['to'])} & "
                    f"{esc(short.get(t['classification'], t['classification']))} & \\texttt{{\\scriptsize {esc(where)}}} \\\\")
    (TEX / "table-transitions.tex").write_text(
        "% Generated by tools/v11/build_wpd_tex.py; do not edit.\n"
        "\\begin{table*}[t]\n\\caption{Implemented Issue-State Transitions at the Evaluated Commit}\\label{tab:transitions}\n"
        "\\centering\\footnotesize\\setlength{\\tabcolsep}{3pt}\n"
        "\\begin{tabular}{@{}p{.22\\textwidth}p{.11\\textwidth}p{.33\\textwidth}p{.08\\textwidth}p{.2\\textwidth}@{}}\\toprule\n"
        "Event & Actor & From $\\to$ to & Status & Source \\\\ \\midrule\n" + "\n".join(rows) +
        "\n\\bottomrule\n\\end{tabular}\n"
        "\\tablenote{}{``Unguarded'': reachable, with no check on the source state. Line numbers refer to the pinned "
        "application export; every citation is located by an exact-substring search when the table is generated.}\n"
        "\\end{table*}\n", encoding="utf-8")

    label = {True: "holds", False: "does not hold"}
    # Manuscript wording of each recorded claim; the recorded claim text stays in the scenario JSON.
    paper_claim = {
        "concurrency_postgres": "Concurrent composition of one version creates no duplicates; an interrupted composition leaves no partial state.",
        "dismissal_memory": "A dismissed finding raised again on a later version arrives dismissed, keyed by category and normalized title (earlier draft).",
        "multi_anchor_supporting_change": "An issue returns for re-check when any of its anchors changes, including a supporting one.",
        "normalisation": "Encoding, newline and size variants of unchanged code keep their anchors.",
        "repeated_composition": "Composing a version repeatedly creates no duplicate issues or attachments.",
        "resolved_reintroduced": "A finding raised again after faculty resolved it creates a new issue; the resolved issue's history stays visible.",
        "three_version_chain_media": "Over three versions an anchor is labeled moved, changed, removed; the issue returns for re-check after the change; voice and image notes follow it.",
        "uncomposed_intermediate_version": "An open issue reaches every later version until faculty close it.",
    }
    assert set(paper_claim) == set(scen), sorted(set(paper_claim) ^ set(scen))
    scen_rows = [f"{esc(paper_claim[k])} & { {'postgresql': 'PostgreSQL', 'sqlite': 'SQLite'}.get(v['engine'], esc(v['engine'])) } & {label[v['claim_holds']]} \\\\" for k, v in scen.items()]
    (TEX / "table-scenarios.tex").write_text(
        "% Generated by tools/v11/build_wpd_tex.py; do not edit.\n"
        "\\begin{table}[t]\n\\caption{State-Contract Scenarios Run Against the Pinned Application}\\label{tab:scenarios}\n"
        "\\centering\\footnotesize\\setlength{\\tabcolsep}{3pt}\n"
        "\\begin{tabular}{@{}p{.57\\columnwidth}p{.17\\columnwidth}p{.18\\columnwidth}@{}}\\toprule\n"
        "Claim checked & Engine & Result \\\\ \\midrule\n" + "\n".join(scen_rows) +
        "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n", encoding="utf-8")
    inputs = {p.relative_to(OUT.parents[1]).as_posix(): sha(p) for p in sorted(OUT.glob("*.json"))}
    inputs.update({p.relative_to(OUT.parents[1]).as_posix(): sha(p) for p in sorted((OUT / "scenarios").glob("*.json"))})
    (TEX / "provenance.json").write_text(json.dumps({"generator": "tools/v11/build_wpd_tex.py",
                                                     "generator_sha256": sha(Path(__file__)), "inputs": inputs,
                                                     "macros": macros}, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(macros, indent=1))


if __name__ == "__main__":
    main()
