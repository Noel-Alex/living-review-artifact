"""Generate the Reproducibility section (full commit hashes, environment, commands, checksums).

Run after build_v11_numbers.py and build_floats.py:
    python -I -B tools/v11/build_repro_tex.py   (from paper-drafts/, Python 3.12)
Every identifier is read from a retained evidence file, never typed.
"""
from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "v11-professor-revision" / "generated"
HEX40 = re.compile(r"^[0-9a-f]{40}$")


def load(rel: str):
    return json.loads((ROOT / rel).read_text(encoding="utf-8"))


def sha(rel: str) -> str:
    return hashlib.sha256((ROOT / rel).read_bytes()).hexdigest()


def brk(x: str) -> str:
    """Typewriter hash with a break point every eight characters, so it fits a column."""
    return r"\texttt{" + r"\allowbreak ".join(x[i:i + 8] for i in range(0, len(x), 8)) + "}"


def h(x: str) -> str:
    assert HEX40.match(x), x
    return brk(x)


def main() -> None:
    public = [("Requests", "requests", "psf/requests"), ("Flask", "flask", "pallets/flask"),
              ("Click", "click", "pallets/click"), ("HTTPX", "httpx", "encode/httpx"),
              ("Rich", "rich", "Textualize/rich")]
    heads = []
    fp = {r["name"]: r for r in load("evidence/public-histories/manifest.json")}
    for name, key, repo in public:
        rep = load(f"evidence/regenerated-history-selection/{key}-report.json")
        assert fp[key]["head"] == rep["head"] and fp[key]["count_matches"], key
        heads.append(rf"{name} (\url{{https://github.com/{repo}}}) at {h(rep['head'])}")
    fp_total = sum(fp[key]["first_parent_count"] for _, key, _ in public)
    tracker = load("evidence/external-comparison/summary.json")["provenance"]
    cm = load("evidence/v11-wpc/codemapper-head.json")
    gt = load("evidence/v11-wpc/gumtree-tag.json")
    sc = load("evidence/v11-wpb2/scaling/results.json")["data"]["corpora"]
    scaling = [rf"Django {c['old']}/{c['new']} at {h(c['old_commit'])}/{h(c['new_commit'])}" if k == "django"
               else rf"CPython {c['old']}/{c['new']} at {h(c['old_commit'])}/{h(c['new_commit'])}"
               for k, c in sc.items()]
    sel_rel = "evidence/v11-wph/private/selected.json"
    sel = load(sel_rel)
    env = load("evidence/v11-wpb2/scaling/results.json")["data"]["environment"]
    sys.path.insert(0, str(ROOT / "tools/vendor"))
    import matplotlib  # noqa: E402
    import numpy  # noqa: E402
    numbers_sha = sha("v11-professor-revision/generated/numbers-v11.tex")
    prov = load("v11-professor-revision/generated/numbers-v11-provenance.json")
    py = env["python"].split()[0]
    stage_py = {}
    for stage in ("compound", "multianchor", "chains"):
        stamped = sorted((ROOT / "evidence/v11-wpb2").glob(f"{stage}-start-*.json"))  # reruns are timestamped
        rel = (f"evidence/v11-wpb2/{stamped[-1].name}" if stamped else f"evidence/v11-wpb2/{stage}-start.json")
        p = load(rel)
        stage_py[stage] = p.get("provenance", p)["python"].split()[0]
    other = sorted({v for v in stage_py.values() if v != py})
    if other:
        odd = [s for s, v in stage_py.items() if v != py]
        names = {"compound": "compound-edit", "multianchor": "multi-anchor", "chains": "resubmission-prefix"}
        py += (" (the " + " and ".join(names[s] for s in odd) + " stages ran under Python "
               + ", ".join(other) + ", recorded in their start files)")
    text = rf"""% Generated by tools/v11/build_repro_tex.py; do not edit.
\section*{{Reproducibility}}
\begingroup\raggedright
\textbf{{Pinned inputs.}} Public real histories: {'; '.join(heads)}, each fetched with Git depth 400, which follows every parent, and traversed by first parent ({fp_total:,} first-parent commits in all). Contextual tracker: \url{{{tracker['implementation']}}} at {h(tracker['revision'])}. CodeMapper: \url{{https://github.com/sola-st/CodeMapper}} at {h(cm['sha'])}. GumTree: release {gt['tag']} at {h(gt['commit'])}. Scale corpora: {'; '.join(scaling)}. The {len(sel)} student-authored repositories are pseudonymized in this paper because they are student work; their URLs and full head hashes are in the selection manifest (SHA-256 {brk(sha(sel_rel))}). The four internal histories and the controlled corpus are private.

\textbf{{Environment.}} Python {py}; NumPy {numpy.__version__} and Matplotlib {matplotlib.__version__} vendored for analysis and figures; CodeMapper and GumTree run in isolated environments whose dependency manifests and hashes are retained with the locator-comparison evidence. Timings come from one workstation ({env['cpu']}, {env['platform'].split('-')[0]}~{env['platform'].split('-')[1]}).

\textbf{{Commands.}} Each work package has a frozen protocol and a runner under \path{{tools/v11/}} (\path{{run_wpb2.py}}, \path{{run_wph2.py}}, \path{{run_wpc.py}}, \path{{run_wpd_tests.py}} and the real-history gate), which writes JSON with the SHA-256 of its code and inputs. \path{{build_v11_numbers.py}} turns those JSON files into every number in the text, \path{{build_floats.py}} and \path{{build_effort_figure.py}} build the remaining floats, and this section is generated by \path{{build_repro_tex.py}}. The macro file has SHA-256 {brk(numbers_sha)} and records the hashes of its {len(prov['inputs'])} input files. Artifact: \url{{https://github.com/Noel-Alex/living-review-artifact}}; its verifier rebuilds every macro from the shipped evidence. Internal histories and student repositories are not released.\par
\endgroup
"""
    (OUT / "reproducibility.tex").write_text(text, encoding="utf-8")
    print("wrote reproducibility.tex")


if __name__ == "__main__":
    main()
