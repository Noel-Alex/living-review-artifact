"""WP K1 strata macros (prefix \\wy) from the latest evidence/v12-wpk1/summary-*.json.

Anchor-length bins and cascade tier x guard-fired cross-tabs, for the v12 text. Writes
v11-professor-revision/generated/numbers-wpkstrata.tex. Picked up by tools/v11/build_wpk_all.py.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / 'evidence/v12-wpk1'
GEN = ROOT / 'v11-professor-revision/generated'
POPS = (('real', 'Real'), ('students', 'Stu'), ('fresh', 'Fr'))
BINS = (('1', 'One'), ('2-3', 'TwoThree'), ('4-9', 'FourNine'), ('>=10', 'Ten'))
METHODS = (('t0.85-deployed', 'Dep'), ('t0.85-IG+AGi+VW', 'Gi'), ('codemapper+quote', 'CmQ'), ('codemapper+IG+AGi', 'CmGi'))


def main():
    found = sorted(EV.glob('summary-*.json'))
    if not found:
        print(f'{Path(__file__).name}: no summary yet; nothing written')
        return
    path = found[-1]
    s = json.loads(path.read_text(encoding='utf-8'))
    mac = {}

    def m(k, v):
        assert k.isalpha(), k
        mac['wy' + k] = v

    for pop, pt in POPS:
        st = s['strata'][pop]
        for b, bt in BINS:
            for meth, mt in METHODS:
                r = st['anchor_span'][b]['methods'][meth]['missed']
                m(pt + bt + mt + 'MissK', f"{r['k']:,}")
                m(pt + bt + mt + 'MissN', f"{r['n']:,}")
                m(pt + bt + mt + 'Miss', f"{100 * r['k'] / r['n']:.1f}" if r['n'] else '--')
        tg = st['cascade_tier_guard_outcomes']
        fired = [v for k, v in tg.items() if k.endswith('guard=True')]
        quiet = [v for k, v in tg.items() if k.endswith('guard=False')]
        for name, group in (('Fired', fired), ('Quiet', quiet)):
            for key, kt in (('n', 'N'), ('changed', 'Changed'), ('missed', 'Miss'), ('false_recheck', 'Extra'),
                            ('wrong_with_recheck', 'Misdir'), ('wrong_silent', 'Silent')):
                m(pt + name + kt, f"{sum(v[key] for v in group):,}")
    text = '% Generated by tools/v11/build_wpkstrata_tex.py from ' + path.name + '; do not edit.\n' + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(mac.items()))
    (GEN / 'numbers-wpkstrata.tex').write_text(text, encoding='utf-8')
    print(f'numbers-wpkstrata.tex: {len(mac)} macros from {path.name}')


if __name__ == '__main__':
    main()
