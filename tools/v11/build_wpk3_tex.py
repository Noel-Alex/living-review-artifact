"""WP K3 macros and tables from the latest evidence/v12-wpk3/summary-*.json.

Writes v11-professor-revision/generated/numbers-wpk3.tex (prefix \\wv), table-interventions.tex (tab:interventions,
compact, for v12), table-interventions-full.tex (tab:interventionsfull, every method, for v11) and
numbers-wpk3-provenance.json. Picked up by tools/v11/build_wpk_all.py.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / 'evidence/v12-wpk3'
GEN = ROOT / 'v11-professor-revision/generated'
METHODS = (('v0.85-off', 'Dep', 'Cascade, deployed'), ('v0.85-off-id', 'DepId', '\\quad +identity rule'),
           ('v0.85-alli', 'Gi', 'Cascade+IG+AGi+VW'), ('v0.85-alli-id', 'GiId', '\\quad +identity rule'),
           ('v0.55-alli', 'Lo', 'Cascade+IG+AGi+VW, $\\theta=0.55$'), ('v0.55-alli-id', 'LoId', '\\quad +identity rule'),
           ('cm-seq-gi', 'Cm', 'CodeMapper+IG+AGi'), ('cm-seq-gi-id', 'CmId', '\\quad +identity rule'))
COMPACT = ('v0.85-off', 'v0.85-off-id', 'cm-seq-gi-id')
COMPACT_LABEL = {'v0.85-off': 'Cascade, deployed', 'v0.85-off-id': 'Cascade, deployed, +identity rule',
                 'cm-seq-gi-id': 'CodeMapper+IG+AGi, +identity rule'}
POL = (('P0', 'PZero', 'none'), ('P1', 'POne', 'correct'), ('P2', 'PTwo', 'accept'), ('P3', 'PThree', 'both'))
MEAS = (('correct', 'Correct'), ('wrong', 'Wrong'), ('lost', 'Lost'), ('missed_last', 'Miss'),
        ('missed_cumulative', 'MissCum'), ('wrong_silent_last', 'Silent'), ('requests_seen', 'Req'),
        ('actions', 'Act'), ('changed', 'Changed'))
COLS = ('correct', 'wrong', 'lost', 'missed_last', 'wrong_silent_last', 'requests_seen', 'actions')


def n(x):
    return f'{x:,}'


def signed(x):
    x = round(x)
    return ('$+$' if x > 0 else '$-$' if x < 0 else '') + f'{abs(x):,}'


def main():
    found = sorted(EV.glob('summary-*.json'))
    if not found:
        print(f'{Path(__file__).name}: no summary yet; nothing written')
        return
    path = found[-1]
    s = json.loads(path.read_text(encoding='utf-8'))
    assert s['gate']['passed'], 'P0 gate failed'
    mac = {}

    def m(k, v):
        assert k.isalpha(), k
        mac['wv' + k] = v

    chains = s['chains_scored']
    m('Chains', n(chains))
    m('Resamples', n(s['resamples']))
    m('GateCmHops', n(s['gate']['cm_hops']))
    m('GateCmAgree', n(s['gate']['cm_hops_agreeing']['cm-seq-gi']))
    m('GateCmIdAgree', n(s['gate']['cm_hops_agreeing']['cm-seq-gi-id']))
    m('GateMismatch', n(s['gate']['cascade_mismatches']))
    for meth, tag, _ in METHODS:
        d = s['methods'][meth]
        for p, pt, _ in POL:
            for key, mt in MEAS:
                m(tag + pt + mt, n(d[p][key]))
            if p != 'P0':
                b = s['paired'][f'{meth}|{p} minus P0']
                for key, mt in MEAS:
                    if key in b:
                        m(tag + 'D' + pt + mt, signed(b[key]['difference']))
                        lo, hi = b[key]['ci95_per_chain']
                        m(tag + 'D' + pt + mt + 'Lo', signed(lo * chains))
                        m(tag + 'D' + pt + mt + 'Hi', signed(hi * chains))
                        # unsigned forms for prose ("raised ... by 217, 189--246"); bounds ordered by magnitude
                        a, z = sorted((abs(round(lo * chains)), abs(round(hi * chains))))
                        m(tag + 'D' + pt + mt + 'Abs', n(abs(round(b[key]['difference']))))
                        m(tag + 'D' + pt + mt + 'AbsLo', n(a))
                        m(tag + 'D' + pt + mt + 'AbsHi', n(z))
        p4 = d['P4']
        m(tag + 'Dismissed', n(p4['dismissed']))
        m(tag + 'DismissedChanged', n(p4['changed_after_dismissal']))
    for key, mt in (('dismissed', 'Dismissed'), ('changed_after_dismissal', 'DismissedChanged')):
        vals = [s['methods'][meth]['P4'][key] for meth, _, _ in METHODS]
        m(mt + 'Min', n(min(vals)))
        m(mt + 'Max', n(max(vals)))
    text = '% Generated by tools/v11/build_wpk3_tex.py from ' + path.name + '; do not edit.\n' + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(mac.items()))
    (GEN / 'numbers-wpk3.tex').write_text(text, encoding='utf-8')

    head = (r'Policy & Correct & Wrong & Lost & \shortstack[r]{Miss,\\last} & \shortstack[r]{Wrong,\\silent} & '
            r'\shortstack[r]{Req-\\uests} & \shortstack[r]{Act-\\ions} \\ \midrule')

    def block(meth, label):
        d = s['methods'][meth]
        out = [r'\multicolumn{8}{@{}l}{\emph{' + label + r'}} \\']
        for p, _, pl in POL:
            out.append(f'\\quad {pl} & ' + ' & '.join(n(d[p][k]) for k in COLS) + r' \\')
        return out

    note = (r'\tablenote{}{\wvChains{} ten-commit chains decidable at commit 10. A simulated supervisor acts at commits 1, 2, 3 and 5, '
            r'only on a request: correct re-anchors a wrong or lost anchor to the reference location (or stops carrying it, issue open, '
            r'if the code is gone); accept marks a correctly placed \lbl{changed} anchor as reviewed; both applies whichever fits. '
            r'Correct, wrong and lost: endpoints at commit 10. Miss, last: code changed since the last supervisor review with no request '
            r'at commit 10. Wrong, silent: wrong endpoints with no request. Requests: requests seen at commits 1, 2, 3, 5 and 10. '
            r'Actions: supervisor actions.}')
    rows = []
    for meth in COMPACT:
        rows += block(meth, COMPACT_LABEL[meth])
    table = (r"""% Generated by tools/v11/build_wpk3_tex.py from """ + path.name + r"""; do not edit.
\begin{table}[t]
\caption{Supervisor Interventions in Ten-Commit Chains}\label{tab:interventions}
\centering\footnotesize
\setlength{\tabcolsep}{2.6pt}
\begin{tabular}{@{}lrrrrrrr@{}}\toprule
""" + head + '\n' + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}
""" + note + r"""
\end{table}
""")
    (GEN / 'table-interventions.tex').write_text(table, encoding='utf-8')
    rows = []
    base = ''
    for meth, _, label in METHODS:
        if label.startswith('\\quad'):
            label = base + ', ' + label.replace('\\quad +', '+')
        else:
            base = label
        rows += block(meth, label)
    full = (r"""% Generated by tools/v11/build_wpk3_tex.py from """ + path.name + r"""; do not edit.
\begin{table}[t]
\caption{Supervisor Interventions in Ten-Commit Chains, Every Method}\label{tab:interventionsfull}
\centering\footnotesize
\setlength{\tabcolsep}{2.6pt}
\begin{tabular}{@{}lrrrrrrr@{}}\toprule
""" + head + '\n' + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}
""" + note + r"""
\end{table}
""")
    (GEN / 'table-interventions-full.tex').write_text(full, encoding='utf-8')
    (GEN / 'numbers-wpk3-provenance.json').write_text(json.dumps(dict(summary=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                                                                      macros=len(mac)), indent=1), encoding='utf-8')
    print(f'numbers-wpk3.tex: {len(mac)} macros from {path.name}')


if __name__ == '__main__':
    main()
