"""Manuscript macros and the external-benchmark table from WP C's frozen summaries (no hand-typed numbers)."""
import json
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from wpa_core import ROOT, sha  # noqa: E402

SRC = ROOT / 'evidence/v11-wpc'
TEX = SRC / 'tex-v11'
METHODS = [('t0.85-deployed', 'Dep', 'Deployed cascade'), ('t0.85-IG+AG+VW', 'All', 'All guards, $\\theta=.85$'),
           ('t0.55-IG+AG+VW', 'AllCal', 'All guards, $\\theta=.55$'), ('cascade_v1', 'Vone', 'Cascade v1'),
           ('tracker_adapter', 'Trk', 'Contextual tracker'), ('gumtree', 'Gt', 'GumTree'), ('codemapper', 'Cm', 'CodeMapper')]
STRATA = [('external:human-AB', 'Hum'), ('external:human-AB:non-Python-code', 'HumNp'), ('external', 'Ext'),
          ('external:variable_test', 'Var'), ('external:block_test', 'Blk'), ('external:method_test', 'Mth'),
          ('real', 'Real'), ('real:oss:targeted', 'RealTgt')]


def load(name):
    d = json.loads((SRC / name).read_text(encoding='utf-8'))
    return d.get('data', d)


def pc(x):
    return '--' if x is None or x.get('rate') is None else f"{100 * x['rate']:.1f}"


def main():
    s = load('evaluation-summary.json')['strata']
    rep = load('codemapper-reproduction-native-final.json')
    macros = {}

    def m(k, v):
        assert k.isalpha(), k
        macros[k] = v
    for stratum, sn in STRATA:
        m(f'cExt{sn}N', f"{s[stratum]['n']:,}")
        for key, mn, _ in METHODS:
            v = s[stratum]['methods'][key]
            m(f'cExt{sn}{mn}Acc', pc(v['accuracy']))
            m(f'cExt{sn}{mn}Miss', pc(v['missed']))
            m(f'cExt{sn}{mn}Silent', pc(v['wrong_silent']))
            m(f'cExt{sn}{mn}False', pc(v['false_recheck']))
            m(f'cExt{sn}{mn}FalseK', f"{v['false_recheck']['k']:,}")
            m(f'cExt{sn}{mn}FalseN', f"{v['false_recheck']['n']:,}")
            m(f'cExt{sn}{mn}Err', f"{v['execution_errors']:,}")
            ch = v.get('characters', {}).get('upstream', {}).get('exact')
            m(f'cExt{sn}{mn}Chars', pc(ch))
    for ds, dn in (('annotation_a', 'A'), ('annotation_b', 'B'), ('suppression', 'Sup'), ('variable_test', 'Var'),
                   ('block_test', 'Blk'), ('method_test', 'Mth')):
        r = rep['datasets'][ds]
        m(f'cRep{dn}Observed', f"{r['observed']['exact']['k']:,}")
        m(f'cRep{dn}Published', f"{r['published']['exact']:.0f}" if r['published']['exact'] > 1 else f"{r['published']['exact']}")
        m(f'cRep{dn}N', f"{r['observed']['n']:,}")
    m('cRepPassed', 'yes' if rep['passed'] else 'no')
    TEX.mkdir(exist_ok=True)
    (TEX / 'numbers-wpc-v11.tex').write_text('% Generated by tools/v11/build_wpc_v11_tex.py; do not edit.\n' +
                                            '\n'.join('\\newcommand{\\' + k + '}{' + v + '}' for k, v in macros.items()) + '\n', encoding='utf-8')
    rows = []
    for key, _, label in METHODS:
        a, b, c = (s['external:human-AB']['methods'][key], s['external:human-AB:non-Python-code']['methods'][key],
                   s['external']['methods'][key])
        ch = a.get('characters', {}).get('upstream', {}).get('exact')
        rows.append(f"{label} & {pc(a['accuracy'])} & {pc(ch)} & {pc(a['missed'])} & {pc(a['wrong_silent'])} & {pc(b['accuracy'])} & {pc(c['accuracy'])} \\\\")
    (TEX / 'table-external.tex').write_text(
        '% Generated by tools/v11/build_wpc_v11_tex.py; do not edit.\n\\begin{table}[t]\n'
        '\\caption{Human-Annotated (Independent) and Multi-Language Benchmarks}\\label{tab:external}\n\\centering\\footnotesize\\setlength{\\tabcolsep}{2.5pt}\n'
        '\\begin{tabular}{@{}lrrrrrr@{}}\\toprule\n & \\multicolumn{4}{c}{Human A/B (' + f"{s['external:human-AB']['n']}" + ')} & Non-Py & All \\\\ '
        '\\cmidrule(lr){2-5}\nMethod & Line & Chars & Missed & Silent & Line & Line \\\\ \\midrule\n' + '\n'.join(rows) +
        f"\n\\bottomrule\n\\end{{tabular}}\n\\tablenote{{}}{{Percentages. Line: file and start line, including correct absence. Chars: exact character region. "
        f"All guards: IG, the original copy guard AG and VW (Table~\\ref{{tab:locator}} uses the corrected AGi). "
        f"CodeMapper: this evaluation's run and change adapter (Table~\\ref{{tab:locator}} uses a later run with the cascade's quotation labels). "
        f"Non-Py: the {s['external:human-AB:non-Python-code']['n']} human-annotated regions outside Python. All: all {s['external']['n']:,} external regions, "
        "including tool-derived Java histories. Living Review sees only the paired files. GumTree execution failures count as incorrect. The pinned CodeMapper is not fully deterministic (Section~\\ref{sec:prefixes}).}\n\\end{table}\n",
        encoding='utf-8')
    inputs = {f'evidence/v11-wpc/{n}': sha(SRC / n) for n in ('evaluation-summary.json', 'codemapper-reproduction-native-final.json')}
    (TEX / 'provenance.json').write_text(json.dumps(dict(generator='tools/v11/build_wpc_v11_tex.py', generator_sha256=sha(Path(__file__)),
                                                         inputs=inputs, macros=macros), indent=1), encoding='utf-8')
    print(len(macros), 'macros')


if __name__ == '__main__':
    main()
