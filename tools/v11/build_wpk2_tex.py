"""WP K2 macros and table from the latest evidence/v12-wpk2/summary-*.json.

Writes v11-professor-revision/generated/numbers-wpk2.tex (prefix \\wp), table-copysuite.tex (tab:copysuite) and
numbers-wpk2-provenance.json. Picked up by tools/v11/build_wpk_all.py.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / 'evidence/v12-wpk2'
GEN = ROOT / 'v11-professor-revision/generated'
METHODS = (('t0.85-deployed', 'Dep', 'Cascade, deployed'), ('t0.85-IG+AG+VW', 'Ag', 'Cascade+IG+AG+VW'),
           ('t0.85-IG+AGi+VW', 'Gi', 'Cascade+IG+AGi+VW'), ('codemapper+quote', 'CmQ', 'CodeMapper+quote'),
           ('codemapper+IG+AG', 'CmAg', '\\quad +IG+AG'), ('codemapper+IG+AGi', 'CmGi', '\\quad +IG+AGi'))
MEAS = (('placement', 'Place'), ('missed', 'Miss'), ('silent', 'Silent'), ('misdirected', 'Misdir'), ('lost', 'Lost'),
        ('unnecessary', 'Extra'), ('errors', 'Err'))
NUM = {'0': 'Zero', '1': 'One', '2': 'Two', '3': 'Three', '4': 'Four', '5': 'Five', '8': 'Eight'}
PLACE = {'adjacent': 'Adj', 'near': 'Near', 'far': 'Far', 'other-file': 'File'}
FATE = {'unchanged': 'Unch', 'shifted': 'Shift', 'token-edit': 'Edit', 'deleted': 'Del'}


def fmt(x):
    return '--' if x is None else f'{x:.1f}'


def main():
    found = sorted(EV.glob('summary-*.json'))
    if not found:
        print(f'{Path(__file__).name}: no summary yet; nothing written')
        return
    path = found[-1]
    s = json.loads(path.read_text(encoding='utf-8'))
    mac = {}

    def m(k, v):
        assert k.isalpha(), k
        mac['wp' + k] = v

    m('N', f"{s['n']:,}")
    m('NMain', f"{s['n_main']:,}")
    m('NSame', f"{s['n_same_revision']:,}")
    m('Sources', str(s['sources']))
    m('Issues', f"{s['issues']['main']['n_issues']:,}")
    for meth, tag, _ in METHODS:
        for key, mt in MEAS:
            r = s['overall'][meth][key]
            m(tag + mt, fmt(r['pct']))
            m(tag + mt + 'K', f"{r['k']:,}")
            m(tag + mt + 'N', f"{r['n']:,}")
            if r['ci'][0] is not None:
                m(tag + mt + 'Lo', fmt(r['ci'][0]))
                m(tag + mt + 'Hi', fmt(r['ci'][1]))
        for group, prefix, names in (('by_c', 'C', NUM), ('by_k', 'K', NUM), ('by_d', 'D', PLACE), ('by_fate', 'F', FATE)):
            for lvl, res in s[group].items():
                for key, mt in MEAS[:6]:
                    m(tag + prefix + names[lvl] + mt, fmt(res[meth][key]['pct']))
        for lvl, res in s['c_by_d'].items():
            c, d = lvl.split('|')
            for key, mt in (('missed', 'Miss'), ('unnecessary', 'Extra')):
                m(tag + 'C' + NUM[c] + PLACE[d] + mt, fmt(res[meth][key]['pct']))
        sr = s['same_revision']
        for key, mt in MEAS[:6]:
            m(tag + 'Same' + mt, fmt(sr['overall'][meth][key]['pct']))
        for lvl, res in sr['by_d'].items():
            m(tag + 'Same' + PLACE[lvl] + 'Miss', fmt(res[meth]['missed']['pct']))
        for part, pt in (('main', ''), ('same_revision', 'Same')):
            iss = s['issues'][part]['methods'][meth]
            for key, mt in (('missed', 'Miss'), ('unnecessary', 'Extra'), ('silent', 'Silent')):
                m(tag + pt + 'Issue' + mt, fmt(iss[key]['pct']))
    tags = {mm: t for mm, t, _ in METHODS}
    for part, pt in (('main', ''), ('with_copies', 'Cp'), ('same_revision', 'Same')):
        for name, r in s['paired'][part]['contrasts'].items():
            a, b = name.split(' minus ')
            for key, mt in MEAS[:6]:
                if key in r:
                    k = f'{pt}D{tags[a]}V{tags[b]}{mt}'
                    m(k, fmt(r[key]['difference_pts']))
                    m(k + 'Lo', fmt(r[key]['ci95_pts'][0]))
                    m(k + 'Hi', fmt(r[key]['ci95_pts'][1]))
    text = '% Generated by tools/v11/build_wpk2_tex.py from ' + path.name + '; do not edit.\n' + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(mac.items()))
    (GEN / 'numbers-wpk2.tex').write_text(text, encoding='utf-8')
    rows = []
    for meth, tag, label in METHODS:
        o = s['overall'][meth]
        cells = [fmt(o[k]['pct']) for k in ('placement', 'missed', 'silent', 'misdirected', 'lost', 'unnecessary')]
        cells += [fmt(s['by_d'][d][meth]['missed']['pct']) for d in PLACE]
        cells += [fmt(s['by_fate']['shifted'][meth]['unnecessary']['pct']), fmt(s['same_revision']['overall'][meth]['missed']['pct']),
                  fmt(s['issues']['main']['methods'][meth]['missed']['pct'])]
        rows.append(label + ' & ' + ' & '.join(cells) + r' \\')
    table = (r"""\begin{table*}[t]
\caption{Parametric Copy Suite: Six Outcomes, Missed Re-Checks by the Nearest Copy, and Two Stress Conditions (\%)}\label{tab:copysuite}
\centering\footnotesize
\setlength{\tabcolsep}{3pt}
\begin{tabular}{@{}lrrrrrrrrrrrrr@{}}\toprule
 & \multicolumn{6}{c}{All held-out trials} & \multicolumn{4}{c}{Miss, nearest copy} & Extra & Miss & Miss \\ \cmidrule(lr){2-7}\cmidrule(lr){8-11}
Method & Place & Miss & Silent & Misdir & Lost & Extra & adj. & $\le$20 & $>$50 & file & shifted & same rev. & issues \\ \midrule
""" + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}
\tablenote{}{\wpNMain{} constructed trials from \wpSources{} source files: 0, 1, 2, 4 or 8 identical copies of the anchored lines before the revision, the nearest adjacent, within 20 lines, more than 50 lines away or in another file, anchors of 1--8 lines, and the original unchanged, shifted by comment lines inserted directly above, token-edited or deleted; 20 trials per cell, every file parses. Nearest-copy columns: trials with at least one copy. Extra, shifted: unnecessary requests on shifted originals. Same rev.: \wpNSame{} trials in which the revision edits or deletes the original and adds one copy. Issues: \wpIssues{} issues of 2--4 anchors, missed when an issue with a changed anchor raises no request.}
\end{table*}
""")
    (GEN / 'table-copysuite.tex').write_text(table, encoding='utf-8')
    (GEN / 'numbers-wpk2-provenance.json').write_text(json.dumps(dict(summary=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                                                                      macros=len(mac)), indent=1), encoding='utf-8')
    print(f'numbers-wpk2.tex: {len(mac)} macros from {path.name}')


if __name__ == '__main__':
    main()
