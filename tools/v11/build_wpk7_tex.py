"""WP K7 macros and table from the latest evidence/v12-wpk7/summary-*.json (ReviewAnchorBench).

Writes v11-professor-revision/generated/numbers-wpk7.tex (prefix \\wr), table-rab.tex and
numbers-wpk7-provenance.json. Picked up by tools/v11/build_wpk_all.py; skips when no summary exists.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EV = ROOT / 'evidence/v12-wpk7'
GEN = ROOT / 'v11-professor-revision/generated'
METHODS = (('t0.85-deployed', 'Dep', 'Cascade, deployed'), ('t0.85-IG+AGi+VW', 'Gi', 'Cascade+IG+AGi+VW'),
           ('codemapper+quote', 'CmQ', 'CodeMapper+quote'), ('codemapper+IG+AG', 'CmAg', '\\quad +IG+AG'),
           ('codemapper+IG+AGi', 'CmGi', '\\quad +IG+AGi'), ('rab-cascade', 'Rab', 'Benchmark$^{a}$'))
MEAS = (('missed', 'Miss'), ('unnecessary', 'Extra'), ('placement', 'Place'), ('lost', 'Lost'), ('silent', 'Silent'),
        ('misdirected', 'Misdir'), ('gone_kept', 'GoneKept'), ('errors', 'Err'), ('ambiguous_request', 'AmbReq'))
STRATA = (('population', 'Pop'), ('heldout', 'Hard'))
FAM = dict(IDENTITY='Identity', PREFIX_INSERT='Prefix', BLOCK_MOVE='Move', REPLACEMENT_APPLIED='Replace',
           MOVE_AND_REPLACE='MoveReplace', TARGET_DELETE='Delete', DUPLICATE_PREIMAGE='Duplicate',
           INTERNAL_LINE_EDIT='Internal', SURROUNDING_CONTEXT_EDIT='Context', WHITESPACE_INSIDE='Whitespace')


def fmt(x):
    return '--' if x is None else f'{x:.1f}'


def main():
    paths = sorted(EV.glob('summary-*.json'))
    if not paths:
        print('no K7 summary; skipped')
        return
    path = paths[-1]
    s = json.loads(path.read_text(encoding='utf-8'))
    mac = {}

    def m(name, value):
        assert name.isalpha(), name
        mac['wr' + name] = value

    sc = s['status_counts']
    for st, tag in STRATA:
        S = s['strata'][st]
        m(tag + 'Cases', f"{S['cases']:,}")
        m(tag + 'Anchors', str(S['anchors']))
        m(tag + 'Repos', str(S['repos']))
        m(tag + 'AllCases', f"{S['rab_all_cases']:,}")
        m(tag + 'Unavailable', str(sc.get(f'{st}/blob-unavailable', 0)))
        m(tag + 'NotRebuilt', f"{sc.get(f'{st}/not-rebuildable', 0):,}")
        for meth, mt, _ in METHODS:
            o = S['seven_family'][meth]
            for key, kt in MEAS:
                r = o[key]
                m(tag + mt + kt, fmt(r['pct']))
                m(tag + mt + kt + 'K', str(r['k']))
                m(tag + mt + kt + 'N', str(r['n']))
                if r['ci'][0] is not None:
                    m(tag + mt + kt + 'Lo', fmt(r['ci'][0]))
                    m(tag + mt + kt + 'Hi', fmt(r['ci'][1]))
        o = S['rab_all_families']['rab-cascade']
        for key, kt in MEAS:
            m(tag + 'RabTen' + kt, fmt(o[key]['pct']))
            m(tag + 'RabTen' + kt + 'K', str(o[key]['k']))
            m(tag + 'RabTen' + kt + 'N', str(o[key]['n']))
        for fam, ft in FAM.items():
            r = S['rab_all_by_family'].get(fam, {}).get('rab-cascade', {})
            for key, kt in (('missed', 'Miss'), ('silent', 'Silent'), ('unnecessary', 'Extra')):
                if key in r:
                    m(tag + 'Rab' + ft + kt + 'K', str(r[key]['k']))
                    m(tag + 'Rab' + ft + kt + 'N', str(r[key]['n']))
        for name, r in S['bootstrap']['contrasts'].items():
            a, b = name.split(' - ')
            ta = next(t for mm, t, _ in METHODS if mm == a)
            tb = next(t for mm, t, _ in METHODS if mm == b)
            for key, kt in MEAS:
                if key in r:
                    m(f'{tag}D{ta}V{tb}{kt}', fmt(r[key]['diff']))
                    m(f'{tag}D{ta}V{tb}{kt}Lo', fmt(r[key]['ci'][0]))
                    m(f'{tag}D{ta}V{tb}{kt}Hi', fmt(r[key]['ci'][1]))
        m(tag + 'Clusters', str(S['bootstrap']['clusters']))
    ex = s['exploratory_amendment_1']
    for st, tag in STRATA:
        for meth, mt, _ in METHODS[:5]:
            d = ex['duplicate_placement'][f'{st}/{meth}']
            m(tag + mt + 'DupOrig', str(d.get('original', 0)))
            v = ex['block_move_requests'][f'{st}/{meth}']
            m(tag + mt + 'MoveCopyReq', str(sum(n for k, n in v.items() if 'pre-existing-copy' in k)))
            m(tag + mt + 'MoveN', str(v['n']))
    ag = s['codemapper_agreement_population']
    m('CmAgreeN', f"{ag.get('n', 0):,}")
    m('CmAgreeK', f"{ag.get('same_start', 0) + ag.get('both_none', 0):,}")
    m('CmErr', str(ag.get('ours_error', 0)))
    text = '% Generated by tools/v11/build_wpk7_tex.py from ' + path.name + '; do not edit.\n' + ''.join(
        f'\\newcommand{{\\{k}}}{{{v}}}\n' for k, v in sorted(mac.items()))
    (GEN / 'numbers-wpk7.tex').write_text(text, encoding='utf-8')
    rows = []
    for meth, mt, label in METHODS:
        cells = []
        for st, _ in STRATA:
            o = s['strata'][st]['seven_family'][meth]
            cells += [fmt(o[k]['pct']) for k in ('missed', 'silent', 'unnecessary', 'ambiguous_request')]
        rows.append(label + ' & ' + ' & '.join(cells) + r' \\')
    table = (r"""\begin{table}[t]
\caption{ReviewAnchorBench: Re-Check Outcomes (\%)}\label{tab:rab}
\centering\footnotesize
\setlength{\tabcolsep}{2pt}
\begin{tabular}{@{}lrrrrrrrr@{}}\toprule
 & \multicolumn{4}{c}{Population-sampled} & \multicolumn{4}{c}{Hard held-out} \\
\cmidrule(lr){2-5}\cmidrule(l){6-9}
Method & Miss & Silent & Extra & Dup & Miss & Silent & Extra & Dup \\ \midrule
""" + '\n'.join(rows) + r"""
\bottomrule
\end{tabular}
\tablenote{}{Seven transformation families rebuilt to the released target hashes: \wrPopCases{} and \wrHardCases{} cases from \wrPopAnchors{} and \wrHardAnchors{} anchors. Miss: changed targets (replacement applied, moved and replaced, deleted) with no re-check request. Silent: wrong placement with no request, over all scored cases. Extra: requests on unchanged targets (identity, prefix insert, block move). Dup: request rate on duplicated pre-images. $^{a}$The benchmark's own cascade: its released predictions, re-scored, not rerun.}
\end{table}
""")
    (GEN / 'table-rab.tex').write_text(table, encoding='utf-8')
    prov = dict(summary=path.name, summary_sha256=hashlib.sha256(path.read_bytes()).hexdigest(), macros=len(mac))
    (GEN / 'numbers-wpk7-provenance.json').write_text(json.dumps(prov, indent=1) + '\n', encoding='utf-8')
    print('numbers-wpk7.tex', len(mac), 'macros')


if __name__ == '__main__':
    main()
