"""Run every WP K macro/table builder (tools/v11/build_wpk*_tex.py) and write generated/numbers-wpk.tex.

numbers-wpk.tex inputs each generated/numbers-wpk*.tex that a builder wrote, so WP K workers never edit
make_v11.py or assemble_v11.py. A builder that fails stops the build.
"""
from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GEN = ROOT / 'v11-professor-revision/generated'


def main() -> None:
    builders = sorted((ROOT / 'tools/v11').glob('build_wpk?*_tex.py'))
    for b in builders:
        r = subprocess.run([sys.executable, '-I', '-B', str(b)], cwd=ROOT, capture_output=True, text=True,
                           encoding='utf-8', errors='replace')
        if r.returncode:
            sys.stdout.write(r.stdout[-3000:] + r.stderr[-3000:])
            raise SystemExit(f'failed: {b.name}')
    parts = sorted(p.name for p in GEN.glob('numbers-wpk?*.tex'))
    text = '% Generated by tools/v11/build_wpk_all.py: WP K macro files.\n' + ''.join(
        f'\\input{{generated/{p[:-4]}}}\n' for p in parts)
    (GEN / 'numbers-wpk.tex').write_text(text, encoding='utf-8')
    print(f'numbers-wpk.tex: {len(builders)} builders, {len(parts)} macro files')


if __name__ == '__main__':
    main()
